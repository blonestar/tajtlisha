#!/usr/bin/env python3
"""
Generates src/shared/logo-font-metrics.generated.ts: advance widths and
vertical metrics of the bundled Noto Sans Bold, so the logo layout (badge and
text widths) is computed identically for the editor preview and the ASS export.
libass does not kern unless the script sets "Kerning: yes", so plain advance
sums match its output (verified: "AVAVAVTo" 519 px vs 518 px computed at 100 px/em).

Dev-only tool, not an app dependency. Run it only when the font changes:

    python3 -m venv /tmp/ftvenv && /tmp/ftvenv/bin/pip install fonttools
    /tmp/ftvenv/bin/python scripts/generate-logo-font-metrics.py
"""

from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "resources" / "fonts" / "NotoSans-Bold.ttf"
OUT = ROOT / "src" / "shared" / "logo-font-metrics.generated.ts"



def main() -> None:
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    os2 = font["OS/2"]

    # Every character the font has, packed as runs of consecutive code points:
    # 'start:adv,adv,...' joined by ';'. Characters outside the table are not
    # supported in logo text (they would fall back to another font).
    runs: list[tuple[int, list[int]]] = []
    for code in sorted(cmap):
        if code < 0x20:
            continue
        advance = hmtx[cmap[code]][0]
        if runs and runs[-1][0] + len(runs[-1][1]) == code:
            runs[-1][1].append(advance)
        else:
            runs.append((code, [advance]))
    entries = [f"{start}:{','.join(str(a) for a in advances)}" for start, advances in runs]
    count = sum(len(advances) for _, advances in runs)

    fallback = hmtx[cmap[ord("n")]][0]
    lines = [
        "// Generated by scripts/generate-logo-font-metrics.py from resources/fonts/NotoSans-Bold.ttf. Do not edit.",
        "",
        "/** Noto Sans Bold metrics in font units (unitsPerEm). */",
        "export const LOGO_FONT_METRICS = {",
        f"  unitsPerEm: {font['head'].unitsPerEm},",
        "  /** OS/2 usWinAscent and usWinDescent: libass puts the baseline winAscent below an \\an7 \\pos. */",
        f"  winAscent: {os2.usWinAscent},",
        f"  winDescent: {os2.usWinDescent},",
        f"  capHeight: {os2.sCapHeight},",
        f"  xHeight: {os2.sxHeight},",
        "  /** Advance used for characters missing from `advances` (the advance of 'n'); normalized logo text has none. */",
        f"  fallbackAdvance: {fallback},",
        "  /** Every character of the font: runs of consecutive code points, 'start:adv,adv,...' joined by ';'. */",
        f"  advances: '{';'.join(entries)}'",
        "} as const;",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT.relative_to(ROOT)} ({count} characters)")


if __name__ == "__main__":
    main()
