#!/usr/bin/env python3
"""
Generates src/shared/watermark-wordmark.generated.ts: the "tajtlisa" (with s-caron) wordmark
as vector outlines from the bundled Noto Sans Bold, so the editor preview (SVG)
and the burned-in export (ASS drawing) draw exactly the same shape.

Dev-only tool, not an app dependency. Run it only when the wordmark changes:

    python3 -m venv /tmp/ftvenv && /tmp/ftvenv/bin/pip install fonttools
    /tmp/ftvenv/bin/python scripts/generate-wordmark.py
"""

from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "resources" / "fonts" / "NotoSans-Bold.ttf"
OUT = ROOT / "src" / "shared" / "watermark-wordmark.generated.ts"
TEXT = "tajtli\u0161a"


def fmt(value: float) -> str:
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


class CubicPathPen(BasePen):
    """Collects outlines as SVG path commands (M, L, C, Z), y pointing down."""

    def __init__(self, glyph_set, dx: float):
        super().__init__(glyph_set)
        self.dx = dx
        self.parts: list[str] = []
        self.xs: list[float] = []
        self.ys: list[float] = []

    def _pt(self, pt) -> str:
        x, y = pt[0] + self.dx, -pt[1]
        self.xs.append(x)
        self.ys.append(y)
        return f"{fmt(x)} {fmt(y)}"

    def _moveTo(self, pt):
        self.parts.append(f"M{self._pt(pt)}")

    def _lineTo(self, pt):
        self.parts.append(f"L{self._pt(pt)}")

    def _curveToOne(self, p1, p2, p3):
        self.parts.append(f"C{self._pt(p1)} {self._pt(p2)} {self._pt(p3)}")

    def _closePath(self):
        self.parts.append("Z")


def main() -> None:
    font = TTFont(FONT)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    units_per_em = font["head"].unitsPerEm

    parts: list[str] = []
    xs: list[float] = []
    ys: list[float] = []
    pen_x = 0.0
    for char in TEXT:
        name = cmap[ord(char)]
        pen = CubicPathPen(glyph_set, pen_x)
        glyph_set[name].draw(pen)
        parts.extend(pen.parts)
        xs.extend(pen.xs)
        ys.extend(pen.ys)
        pen_x += hmtx[name][0]

    os2 = font["OS/2"]
    OUT.write_text(
        "// Generated by scripts/generate-wordmark.py from resources/fonts/NotoSans-Bold.ttf. Do not edit.\n"
        "\n"
        "/** The \"tajtli\\u0161a\" wordmark as outlines in font units, y down, baseline at y = 0. */\n"
        "export const WORDMARK = {\n"
        f"  unitsPerEm: {units_per_em},\n"
        f"  /** Advance width of the whole word. */\n"
        f"  advance: {fmt(pen_x)},\n"
        f"  /** x-height and cap height above the baseline (positive numbers). */\n"
        f"  xHeight: {os2.sxHeight},\n"
        f"  capHeight: {os2.sCapHeight},\n"
        f"  /** Ink bounds of the outlines. */\n"
        f"  minX: {fmt(min(xs))},\n"
        f"  maxX: {fmt(max(xs))},\n"
        f"  minY: {fmt(min(ys))},\n"
        f"  maxY: {fmt(max(ys))},\n"
        "  /** SVG path data using only absolute M, L, C and Z commands. */\n"
        f"  path: '{' '.join(parts)}'\n"
        "} as const;\n",
        encoding="ascii",
        errors="strict",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
